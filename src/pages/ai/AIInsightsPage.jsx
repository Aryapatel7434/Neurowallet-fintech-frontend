
import React, { useCallback, useEffect, useState } from "react";
import {
    getAIInsights,
    getFinancialScore,
    getBudgetHealth,
    getGoalRecommendation,
} from "../../services/aiService";
import "./aiInsightsPage.css";

const resources = [
    {
        key: "insights",
        title: "Financial Insights",
        description: "Insights generated by the backend",
        load: getAIInsights,
    },
    {
        key: "score",
        title: "Financial Health Score",
        description: "Your reported financial health assessment",
        load: getFinancialScore,
    },
    {
        key: "budget",
        title: "Budget Health",
        description: "Your reported budget assessment",
        load: getBudgetHealth,
    },
    {
        key: "goals",
        title: "Goal Recommendations",
        description: "Recommendations returned by the backend",
        load: getGoalRecommendation,
    },
];

function unwrapResponse(response) {
    if (
        response &&
        typeof response === "object" &&
        Object.prototype.hasOwnProperty.call(response, "data")
    ) {
        return response.data;
    }

    return response;
}

function formatLabel(value) {
    return value
        .replace(/([a-z])([A-Z])/g, "$1 $2")
        .replace(/[_-]/g, " ")
        .replace(/\b\w/g, (letter) => letter.toUpperCase());
}

function formatValue(value) {
    if (value === null || value === undefined || value === "") {
        return "Not provided";
    }

    if (typeof value === "boolean") {
        return value ? "Yes" : "No";
    }

    if (typeof value === "number") {
        return value.toLocaleString("en-IN", {
            maximumFractionDigits: 2,
        });
    }

    if (Array.isArray(value)) {
        return value.length
            ? `${value.length} item${value.length === 1 ? "" : "s"}`
            : "None reported";
    }

    if (typeof value === "object") {
        return "Details available";
    }

    return String(value);
}

function DataFields({ data, depth = 0 }) {
    if (data === null || data === undefined) {
        return <p className="ai-empty">No data was returned.</p>;
    }

    if (Array.isArray(data)) {
        if (data.length === 0) {
            return <p className="ai-empty">No items reported.</p>;
        }

        return (
            <div className="ai-list">
                {data.map((item, index) => (
                    <article className="ai-list-item" key={index}>
                        {typeof item === "object" && item !== null ? (
                            <DataFields data={item} depth={depth + 1} />
                        ) : (
                            <p>{formatValue(item)}</p>
                        )}
                    </article>
                ))}
            </div>
        );
    }

    if (typeof data !== "object") {
        return <p>{formatValue(data)}</p>;
    }

    const entries = Object.entries(data).filter(
        ([, value]) => value !== undefined
    );

    if (entries.length === 0) {
        return <p className="ai-empty">No details were provided.</p>;
    }

    return (
        <div className={depth === 0 ? "ai-data-grid" : "ai-nested-data"}>
            {entries.map(([key, value]) => {
                const nested =
                    value !== null && typeof value === "object";

                return (
                    <div className="ai-data-field" key={key}>
                        <span className="ai-field-label">
                            {formatLabel(key)}
                        </span>

                        {nested ? (
                            <div className="ai-field-nested">
                                <DataFields
                                    data={value}
                                    depth={depth + 1}
                                />
                            </div>
                        ) : (
                            <strong className="ai-field-value">
                                {formatValue(value)}
                            </strong>
                        )}
                    </div>
                );
            })}
        </div>
    );
}

function AIInsightsPage() {
    const [data, setData] = useState({});
    const [loading, setLoading] = useState(true);
    const [errors, setErrors] = useState({});
    const [lastUpdated, setLastUpdated] = useState(null);

    const loadData = useCallback(async () => {
        setLoading(true);

        const results = await Promise.allSettled(
            resources.map((resource) => resource.load())
        );

        const nextData = {};
        const nextErrors = {};

        results.forEach((result, index) => {
            const key = resources[index].key;

            if (result.status === "fulfilled") {
                nextData[key] = unwrapResponse(result.value);
            } else {
                nextErrors[key] =
                    result.reason?.response?.data?.message ||
                    result.reason?.message ||
                    "Unable to load this resource.";
            }
        });

        setData(nextData);
        setErrors(nextErrors);
        setLastUpdated(new Date());
        setLoading(false);
    }, []);

    useEffect(() => {
        loadData();
    }, [loadData]);

    const failedCount = Object.keys(errors).length;

    return (
        <main className="ai-insights-page">
            <header className="ai-page-header">
                <div>
                    <p className="ai-eyebrow">NEUROWALLET INTELLIGENCE</p>
                    <h1>AI Financial Insights</h1>
                    <p className="ai-page-description">
                        Explore financial assessments and recommendations
                        returned by your NeuroWallet backend.
                    </p>
                </div>

                <button
                    className="ai-refresh-button"
                    type="button"
                    onClick={loadData}
                    disabled={loading}
                >
                    {loading ? "Refreshing..." : "Refresh data"}
                </button>
            </header>

            {loading && Object.keys(data).length === 0 && (
                <div className="ai-status-panel" role="status">
                    Loading financial insights...
                </div>
            )}

            {!loading && failedCount > 0 && (
                <div className="ai-error-banner" role="alert">
                    {failedCount === resources.length
                        ? "Unable to load AI data. Check your authentication and backend service."
                        : `${failedCount} section(s) could not be loaded. Available sections are still shown below.`}
                </div>
            )}

            <section className="ai-resource-grid">
                {resources.map((resource) => {
                    const hasData = Object.prototype.hasOwnProperty.call(
                        data,
                        resource.key
                    );

                    const failed = Boolean(errors[resource.key]);

                    return (
                        <article
                            className="ai-resource-card"
                            key={resource.key}
                        >
                            <div className="ai-card-heading">
                                <div>
                                    <h2>{resource.title}</h2>
                                    <p>{resource.description}</p>
                                </div>

                                <span
                                    className={`ai-status-tag ${
                                        failed
                                            ? "ai-status-error"
                                            : hasData
                                              ? "ai-status-success"
                                              : "ai-status-pending"
                                    }`}
                                >
                                    {failed
                                        ? "Unavailable"
                                        : hasData
                                          ? "Received"
                                          : loading
                                            ? "Loading"
                                            : "No data"}
                                </span>
                            </div>

                            {failed ? (
                                <div className="ai-section-error">
                                    <p>{errors[resource.key]}</p>
                                    <button
                                        type="button"
                                        onClick={loadData}
                                        disabled={loading}
                                    >
                                        Try again
                                    </button>
                                </div>
                            ) : hasData ? (
                                <DataFields data={data[resource.key]} />
                            ) : (
                                <p className="ai-empty">
                                    {loading
                                        ? "Waiting for backend response..."
                                        : "No response available."}
                                </p>
                            )}
                        </article>
                    );
                })}
            </section>

            <footer className="ai-page-footer">
                <span>
                    Data source: authenticated NeuroWallet API
                </span>

                <span>
                    {lastUpdated
                        ? `Last checked: ${lastUpdated.toLocaleTimeString()}`
                        : "Not yet checked"}
                </span>
            </footer>
        </main>
    );
}

export default AIInsightsPage;
